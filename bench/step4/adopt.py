def qualification_record() -> dict:
    """Everything the qualification freezes: route, H, op, goals, cases, schedule, the 36 request digests, caps, rules
    and the sample packets (one per cell and the clean-fixture classify packet). Raises AdoptError on any problem."""
    problems = case_problems() + W.limits_problems() + W.graph_problems()
    if hashlib.sha256(SYSTEM.encode('utf-8')).hexdigest() != B.SYSTEM_SHA:
        problems.append('H differs from the frozen text')
    reqs = requests()
    slots = []
    for slot in schedule():
        r = reqs[slot['slot']]
        members = [(case(slot['goal'], k)['record'], case(slot['goal'], k)['interval']) for k in slot['cases']]
        problems += [f"slot {slot['slot']}: {p}" for p in packet_problems(r['prompt'], goal_text(slot['goal']),
                                                                          members)]
        if r['system'] != SYSTEM:
            problems.append(f"slot {slot['slot']}: system text is not H")
        slots.append({'slot': slot['slot'], 'cell': slot['cell'], 'goal': slot['goal'], 'cases': slot['cases'],
                      'direction': slot['direction'], 'expected': slot['expected'],
                      'prompt_sha256': B.sha(r['prompt']), 'prompt_bytes': len(r['prompt'].encode('utf-8'))})
    clean = clean_packet()
    problems += ['clean packet: ' + p for p in packet_problems(clean['prompt'], spec()['goal'],
                                                                workflow_members('rev1'))]
    if problems:
        raise AdoptError('; '.join(problems[:8]))
    q = qual()
    return {'plan': PLAN_ID,
            'route': {'model': q['model'], 'effort': q['effort'], 'cli_version': q['cli_version'],
                      'argv': B.call_argv('<H>'), 'prompt_via': 'stdin, utf-8 bytes',
                      'forbidden_env': list(B.FORBIDDEN_ENV), 'parser': 'oz1g-header strict (boundary.py parse_reply)',
                      'usage': 'modelUsage only'},
            'system_sha256': B.SYSTEM_SHA, 'operation': spec()['model_ops']['model.classify'],
            'limits': spec()['limits'], 'goal_template': spec()['goal_template'],
            'goals': {g: goal_text(g) for g in sorted(goals())},
            'cases': [{k: c[k] for k in ('id', 'record', 'interval', 'label')} for c in q['cases']],
            'slots': slots, 'caps': {'qualification': q['caps'], 'suite': G.allocation()}, 'rules': q['rules'],
            'samples': {'size4': reqs[1]['prompt'], 'size1': reqs[13]['prompt'], 'clean_classify': clean['prompt']}}


def _digest(record: dict) -> str:
    return B.sha(B.canon(record))


def freeze(write: bool = False, *, full: bool = True) -> dict:
    """G0. full=False checks the files only (the qualification part is a deterministic function of them); full=True
    also regenerates the 36 packets and the samples and compares them with the stored record."""
    stored = json.loads(FREEZE_FILE.read_text(encoding='utf-8')) if FREEZE_FILE.exists() else {}
    files = files_record()
    problems = []
    if write or full:
        try:
            qualification = qualification_record()
        except AdoptError as exc:
            if write:
                raise
            return {'frozen': False, 'digest': stored.get('digest'), 'current_digest': None,
                    'problems': ['qualification: ' + str(exc)]}
    else:
        qualification = stored.get('qualification', {})
    current = {'files': files, 'qualification': qualification}
    digest = _digest(current)
    if write:
        FREEZE_FILE.write_text(json.dumps(dict(current, digest=digest), indent=1, ensure_ascii=False) + '\n',
                               encoding='utf-8', newline='\n')
        return {'frozen': True, 'digest': digest, 'current_digest': digest, 'problems': []}
    if stored.get('digest') != _digest({'files': stored.get('files', {}),
                                        'qualification': stored.get('qualification', {})}):
        problems.append('the stored record does not hash to the stored digest')
    for group in ('pack', 'code', 'design'):
        for name, value in files[group].items():
            if stored.get('files', {}).get(group, {}).get(name) != value:
                problems.append(f'{name} changed since the freeze')
        for name in set(stored.get('files', {}).get(group, {})) - set(files[group]):
            problems.append(f'{name} missing')
    if full and json.loads(json.dumps(qualification)) != stored.get('qualification'):
        problems.append('the regenerated qualification record differs from the stored one')
    return {'frozen': not problems, 'digest': stored.get('digest'), 'current_digest': digest, 'problems': problems}


def freeze_status() -> dict:
    """The suite's freeze check (files only; step4.py's flow requests and live guards call it)."""
    return freeze(full=False)


