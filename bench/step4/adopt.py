def qual_fixture_runner(plan: dict, clock_ref: list, *, seconds: float = 6.0):
    """Answers each slot from its own packet (oracle labels), or as plan says for that invocation number: 'wrong',
    'malformed', 'missing_usage', 'wrong_model', 'timeout', 'slow' (past 300 s) or a fixed token count."""
    calls = []

    def run_one(request, timeout, _calls=calls):
        n = len(_calls) + 1
        _calls.append(request)
        case_ = plan.get(n, 'pass')
        clock_ref[0] += seconds
        body = json.loads(request['prompt'])
        lower, upper = (Decimal(x) for x in body['goal'].split('[', 1)[1].split(']', 1)[0].split(','))
        answers = {row[0]: oracle_label(body['refs'][row[2]], lower, upper) for block in body['jobs']
                   for row in block[1:]}
        if case_ == 'timeout':
            clock_ref[0] += timeout
            return None, b'', b'', True
        if case_ == 'wrong':
            first = next(iter(answers))
            answers[first] = 'inside' if answers[first] != 'inside' else 'outside'
        reply = 'Here are the answers.' if case_ == 'malformed' else encode_reply(answers)
        options = {'usage': case_ != 'missing_usage', 'thinking': 0}
        if case_ == 'wrong_model':
            options['model'] = 'claude-haiku-4-5'
        if isinstance(case_, int):
            options['tokens'] = (2, 0, case_ - 63, 61)
        if case_ == 'slow':
            clock_ref[0] += 400
        return 0, json.dumps(B.fixture_envelope(reply, **options)).encode('utf-8'), b'', False

    run_one.calls = calls
    return run_one


def qualification_dry(base: Path, record: dict) -> dict:
    """The qualification run loop on fixture replies (no process is ever started)."""
    out = {}
    shutil.rmtree(base, ignore_errors=True)

    def scenario(name, plan, gap=0.0):
        clock = [1000.0]
        runner = qual_fixture_runner(plan, clock)

        def log(*_):  # wall time passing between the calls (each launch and end logs once)
            clock[0] += gap
        result = run_qualification(base / name, record['digest'], runner, clock=lambda: clock[0], log=log,
                                   record=record)
        return result, runner

    result, runner = scenario('pass', {})
    analysis = analyze_qualification(base / 'pass')
    again, runner2 = scenario('pass', {})
    order = [(json.loads(r['prompt'])['goal'], len(json.loads(r['prompt'])['jobs'][0]) - 1) for r in runner.calls]
    out['all_36_pass_size4_first'] = {
        'pass': (result == {'launched': 36, 'stopped': 'schedule complete'} and analysis['pass']
                 and [n for _, n in order] == [4] * 12 + [1] * 24 and again['launched'] == 0
                 and [r['prompt'] for r in runner.calls] == [requests()[s['slot']]['prompt'] for s in schedule()]),
        'result': result, 'cells': {k: v['verdict'] for k, v in analysis['cells'].items()}}
    result, runner = scenario('wrong5', {5: 'wrong'})
    analysis = analyze_qualification(base / 'wrong5')
    again, _ = scenario('wrong5', {})
    out['wrong_label_stops_the_attempt'] = {
        'pass': (result['launched'] == 5 and result['stopped'].startswith('terminal halt') and again['launched'] == 0
                 and analysis['cells']['size4']['verdict'] == 'fail'
                 and analysis['cells']['size1']['verdict'] == 'untested' and not analysis['pass']),
        'result': result, 'cells': {k: v['verdict'] for k, v in analysis['cells'].items()}}
    result, _ = scenario('single', {20: 'malformed'})
    analysis = analyze_qualification(base / 'single')
    out['wire_rejection_in_the_singleton_cell'] = {
        'pass': (result['launched'] == 20 and analysis['cells']['size4']['verdict'] == 'pass'
                 and analysis['cells']['size1']['verdict'] == 'fail'), 'result': result}
    for name, plan, key in (('route', {3: 'wrong_model'}, 'route mismatch'),
                            ('usage', {2: 'missing_usage'}, 'accounting incomplete'),
                            ('timeout', {4: 'timeout'}, 'deadline'), ('slow', {4: 'slow'}, 'not on time')):
        result, _ = scenario(name, plan)
        again, _ = scenario(name, {})
        out[f'{name}_is_terminal'] = {'pass': (key in result['stopped'] and again['launched'] == 0
                                               and not analyze_qualification(base / name)['pass']),
                                      'result': result}
    result, _ = scenario('ceiling', {n: 30000 for n in range(1, 37)})
    out['token_ceiling_admission'] = {'pass': result['launched'] == 4 and result['stopped'].startswith('token ceiling'),
                                      'result': result}
    result, _ = scenario('time', {}, gap=1500.0)
    out['four_hour_envelope'] = {'pass': result['stopped'] == 'overall time cap reached' and result['launched'] == 5,
                                 'result': result}
    store = B.Store(base / 'orphan')
    store.append({'event': 'plan', 'plan': PLAN_ID, 'digest': record['digest'], 'ts': 1.0, 'caps': qual()['caps']})
    store.append({'event': 'launch', 'slot': 1, 'arm': 'q4', 'call_id': 'x', 'ts': 2.0})
    result, _ = scenario('orphan', {})
    again, _ = scenario('orphan', {})
    analysis = analyze_qualification(base / 'orphan')
    out['unfinished_launch_is_terminal'] = {
        'pass': ('never recorded as finished' in result['stopped'] and again['launched'] == 0
                 and analysis['cells']['size4']['verdict'] == 'fail'), 'result': result}
    try:
        run_qualification(base / 'expect', '0' * 64, qual_fixture_runner({}, [0.0]), record=record)
        out['wrong_digest_refused'] = {'pass': False}
    except AdoptError as exc:
        out['wrong_digest_refused'] = {'pass': 'nothing was launched' in str(exc)}
    return out


@contextlib.contextmanager
def _fixture_case(ws: Path, mode: dict | None = None):
    """A fresh fixture workspace (OZ_FIXTURE_DIR restored afterwards)."""
    saved = os.environ.get('OZ_FIXTURE_DIR')
    try:
        if ws.exists():
            shutil.rmtree(ws)
        S.prepare(ws, 'fixture')
        if mode:
            (ws / 'fixture' / 'mode.json').write_text(json.dumps(mode), encoding='utf-8')
        yield ws
    finally:
        if saved is None:
            os.environ.pop('OZ_FIXTURE_DIR', None)
        else:
            os.environ['OZ_FIXTURE_DIR'] = saved


