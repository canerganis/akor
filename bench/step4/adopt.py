# ---- the 24 cases (independent Decimal recomputation, and the workflow's own host arithmetic) ----

def _mm(text: str) -> Decimal:
    number, unit = text.split(' ')
    if unit != 'mm' or len(number.split('.')[-1]) != 2:
        raise AdoptError('not a two-decimal mm value: ' + text)
    return Decimal(number)


def table_interval(case: int, lower: Decimal, upper: Decimal):
    """The case table as signed (Opus section 4, 0.01 breaches), from the goal limits alone."""
    d1, d2, d5 = Decimal('0.01'), Decimal('0.02'), Decimal('0.05')
    pair = {1: (lower, upper), 2: (lower, upper - d2), 3: (lower + d2, upper), 4: (lower + d1, upper - d1),
            5: (lower - d1, lower + d1), 6: (upper - d1, upper + d1), 7: (upper + d1, upper + d5)}.get(case)
    return 'unknown' if pair is None else [f'{pair[0]:.2f} mm', f'{pair[1]:.2f} mm']


def oracle_label(interval, lower: Decimal, upper: Decimal) -> str:
    if interval == 'unknown':
        return 'unknown'
    return 'inside' if _mm(interval[0]) >= lower and _mm(interval[1]) <= upper else 'outside'


def goals() -> dict:
    return {g['goal']: (g['lower'], g['upper']) for g in qual()['goals']}


def goal_text(goal: int) -> str:
    lower, upper = goals()[goal]
    return spec()['goal_template'].format(lower=lower, upper=upper)


def case_problems() -> list:
    """Every frozen case against the signed table: its interval from the goal limits, its record consistent with it on
    the host (the workflow's Decimal parser, two-decimal mm, 0.01 breaches included), its label from an independent
    oracle and from the table, and the metadata fields of a workflow record."""
    q, problems = qual(), []
    table = {row['case']: row for row in q['case_table']}
    if [row['case'] for row in q['case_table']] != list(range(1, 9)):
        problems.append('the case table is not cases 1 to 8')
    if goals() != {1: ('12.48', '12.52'), 2: ('10.00', '10.08'), 3: ('12.46', '12.54')}:
        problems.append('the goals are not the three signed goals')
    if q['quartets'] != [[1, 5, 3, 8], [2, 6, 4, 7]] or q['singleton_order'] != [1, 5, 3, 8, 2, 6, 4, 7]:
        problems.append('quartets or singleton order differ from the signed ones')
    seen = set()
    for c in q['cases']:
        lower, upper = (Decimal(x) for x in goals()[c['goal']])
        where = c['id']
        seen.add((c['goal'], c['case']))
        if c['id'] != f"g{c['goal']}c{c['case']}":
            problems.append(f'{where}: id')
        if c['interval'] != table_interval(c['case'], lower, upper):
            problems.append(f'{where}: interval is not the table interval')
        try:
            fields = W.parse_record(c['record'])
            if W.bounds_of(fields) != c['interval']:
                problems.append(f'{where}: the record does not recompute to the interval on the host')
        except Exception as exc:  # noqa: BLE001
            problems.append(f'{where}: the record does not parse on the host ({exc})')
            continue
        if fields['uncertainty'] != 'unknown' and _mm(fields['uncertainty']) != (
                _mm(c['interval'][1]) - _mm(c['interval'][0])) / 2:
            problems.append(f'{where}: uncertainty is not half the interval width')
        if fields['physical_validation'] != 'not_claimed' or not fields['n'].isdigit():
            problems.append(f'{where}: metadata fields')
        label = oracle_label(c['interval'], lower, upper)
        if not (c['label'] == label == table[c['case']]['label']):
            problems.append(f'{where}: label {c["label"]} != oracle {label} or table {table[c["case"]]["label"]}')
    if seen != {(g, k) for g in (1, 2, 3) for k in range(1, 9)} or len(q['cases']) != 24:
        problems.append('the cases are not exactly 8 per goal for 3 goals')
    return problems


def case(goal: int, number: int) -> dict:
    return next(c for c in qual()['cases'] if c['goal'] == goal and c['case'] == number)


# ---- schedule and packets (generated by the workflow's own planning and packing code) ----

def schedule() -> list:
    """The frozen run order: per goal quartet one forward and reversed, then quartet two forward and reversed (12
    size-4 calls); then singletons by case in singleton_order, each across the three goals (24 calls)."""
    q, out = qual(), []
    for g in sorted(goals()):
        for quartet in q['quartets']:
            for direction, cases in (('forward', quartet), ('reversed', list(reversed(quartet)))):
                out.append({'cell': 'size4', 'arm': 'q4', 'goal': g, 'cases': cases, 'direction': direction})
    for number in q['singleton_order']:
        for g in sorted(goals()):
            out.append({'cell': 'size1', 'arm': 'q1', 'goal': g, 'cases': [number], 'direction': 'single'})
    for i, slot in enumerate(out, 1):
        slot['slot'] = i
        slot['ids'] = qual()['job_ids'][:len(slot['cases'])]
        slot['expected'] = {j: case(slot['goal'], k)['label'] for j, k in zip(slot['ids'], slot['cases'])}
    return out


class Capture:
    """In-process adapter for packet generation: records the request and answers each job with the oracle label of
    its own two refs under the packet's goal (no model, no process)."""
    capabilities = CAPS

    def __init__(self):
        self.requests = []

    def __call__(self, request):
        self.requests.append({'system': request['system'], 'prompt': request['prompt']})
        body = json.loads(request['prompt'])
        lower, upper = (Decimal(x) for x in body['goal'].split('[', 1)[1].split(']', 1)[0].split(','))
        answers = {row[0]: oracle_label(body['refs'][row[2]], lower, upper) for block in body['jobs']
                   for row in block[1:]}
        return {'reply': encode_reply(answers), 'usage': {'input_tokens': 1, 'output_tokens': 1}}


def classify_op(goal: str | None = None) -> ModelOp:
    """The registered model.classify v2 of the v2 workflow, optionally with another goal (the qualification goals are
    the workflow's goal sentence with only the two numbers replaced)."""
    op = W.registry()['model.classify']
    return op if goal is None else replace(op, goal=goal)


def stage_packet(goal: str, members: list, *, rid: str = 'qgen', checks=False) -> dict:
    """{'system','prompt'}: the packet the executor builds for one classify stage of these members [(record, interval)],
    job IDs classify_A.. by position: oz_flow's stage request, then oz do (normalize, inbox, ref reads, planner,
    renderer) with the workflow's packet sizes, under a capturing adapter in a scratch workspace."""
    op = classify_op(goal)
    if not checks:
        op = replace(op, checks=())  # the packet bytes do not depend on checks; other goals have other limits
    nodes = qual()['job_ids'][:len(members)]
    req = _stage_request(rid, op, nodes, {n: [r, i] for n, (r, i) in zip(nodes, members)}, {n: 1 for n in nodes},
                         3600, 300, spec()['route']['model'], 100000)
    adapter = Capture()
    with tempfile.TemporaryDirectory(prefix='adq') as tmp:
        from oz_workspace import initialize
        initialize(Path(tmp))
        result = do(req, workspace=tmp, adapter=adapter, registry=W.CHECKS,
                    packet_sizes=tuple(spec()['packets']['sizes']),
                    experimental_sizes=tuple(spec()['packets']['experimental_sizes']))
    if result['status'] != 'complete' or len(adapter.requests) != 1:
        raise AdoptError(f'packet generation did not give exactly one call: {result["status"]}')
    return adapter.requests[0]


_REQUESTS: dict = {}


def requests() -> dict:
    """{slot: {'system','prompt'}} for the 36 scheduled calls (cached per process)."""
    if not _REQUESTS:
        for slot in schedule():
            members = [(case(slot['goal'], k)['record'], case(slot['goal'], k)['interval']) for k in slot['cases']]
            _REQUESTS[slot['slot']] = stage_packet(goal_text(slot['goal']), members, rid=f"q{slot['slot']:02d}")
    return dict(_REQUESTS)


