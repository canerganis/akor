# ---- the qualification run (resumable, sequential, stops at the first failure) ----

def evaluate(exit_code, timed_out: bool, elapsed_ms: int, stdout: bytes, expected: dict, call_seconds: int) -> dict:
    """The judgement of one qualification call from its raw evidence, scored against its frozen labels. outcome:
    deadline, process_failure, wire_rejected, model_error, semantic or correct (in that priority). passed means
    entirely correct, on time, route ok and accounting complete."""
    ids = list(expected)
    ev = {'exit_code': exit_code, 'timed_out': bool(timed_out), 'elapsed_ms': elapsed_ms,
          'on_time': (not timed_out) and elapsed_ms <= call_seconds * 1000, 'envelope_ok': False,
          'usage': B.model_usage(None), 'route': 'unknown', 'reject_reason': None, 'members': {},
          'correct_members': 0, 'model_error_lines': 0, 'entirely_correct': False, 'passed': False}
    envelope = None
    try:
        envelope = json.loads(stdout.decode('utf-8'), parse_constant=B._no_const)
    except (ValueError, UnicodeError):
        pass
    if isinstance(envelope, dict):
        ev['envelope_ok'] = True
        ev['usage'] = B.model_usage(envelope)
        if ev['usage']['models'] is not None:
            ev['route'] = 'ok' if ev['usage']['models'] == [qual()['model']] else 'mismatch'
    result = envelope.get('result') if isinstance(envelope, dict) else None
    failed = (exit_code != 0 or not ev['envelope_ok'] or envelope.get('is_error') is True
              or envelope.get('subtype', 'success') != 'success' or not isinstance(result, str))
    if timed_out:
        ev['outcome'] = 'deadline'
        return ev
    if failed:
        ev['outcome'] = 'process_failure'
        return ev
    parsed = B.parse_reply(result, ids)
    if not parsed['ok']:
        ev['outcome'], ev['reject_reason'] = 'wire_rejected', parsed['reason']
        return ev
    for job in ids:
        record = parsed['entries'][job]
        right = record[0] == 'value' and type(record[1]) is str and record[1] == expected[job]
        ev['members'][job] = {'got': record[1] if record[0] == 'value' else list(record[1:]), 'kind': record[0],
                              'expected': expected[job], 'correct': right}
        ev['model_error_lines'] += record[0] == 'error'
    ev['correct_members'] = sum(m['correct'] for m in ev['members'].values())
    ev['outcome'] = ('model_error' if ev['model_error_lines'] else 'semantic' if ev['correct_members'] < len(ids)
                     else 'correct')
    ev['entirely_correct'] = ev['outcome'] == 'correct' and ev['on_time']
    ev['passed'] = ev['entirely_correct'] and ev['route'] == 'ok' and ev['usage']['complete']
    return ev


def _spent(ends: dict, reserve: int) -> int:
    return sum(e['evaluation']['usage']['total'] if e['evaluation']['usage']['complete'] else reserve
               for e in ends.values())


def run_qualification(out: Path, expect: str, runner=B.live_runner, *, clock=time.time, preflight=None, log=print,
                      record=None) -> dict:
    """Launch the remaining slots in the frozen order. Resumable: a finished slot is never run again. Stops at the
    first of: a call that does not pass (terminal: the attempt has failed; a second attempt is a new
    preregistration), an unfinished launch (terminal, counted, never retried), a cap, the end of the schedule."""
    record = record or freeze()
    if not record.get('frozen') or expect != record.get('digest'):
        raise AdoptError(f'--expect {expect} is not a held freeze digest ({record.get("digest")}); nothing was launched')
    if preflight is not None:
        problems = preflight()
        if problems:
            raise AdoptError('preflight failed: ' + '; '.join(problems) + '; nothing was launched')
    caps = qual()['caps']
    store = B.Store(out)
    events, problems = store.events()
    if problems:
        raise AdoptError('ledger integrity: ' + '; '.join(problems) + '; nothing was launched')
    state = B.state_of(events)
    if state['plan'] and state['plan']['digest'] != expect:
        raise AdoptError('this evidence directory belongs to another freeze digest; use a fresh directory')
    if not state['plan']:
        store.append({'event': 'plan', 'plan': PLAN_ID, 'digest': expect, 'ts': clock(), 'caps': caps})
    seq = sum(1 for e in events if e.get('event') == 'halt')
    launched = 0

    def halt(reason):
        nonlocal seq
        seq += 1
        store.append({'event': 'halt', 'seq': seq, 'reason': reason, 'terminal': True, 'ts': clock()})
        return {'launched': launched, 'stopped': 'terminal halt: ' + reason}

    if state['orphans']:
        if not state['open_halt']:
            return halt(f"slot {state['orphans'][0]} was launched but never recorded as finished")
        return {'launched': 0, 'stopped': 'terminal halt: ' + state['open_halt']['reason']}
    if state['open_halt']:
        return {'launched': 0, 'stopped': 'terminal halt: ' + state['open_halt']['reason']}
    reqs = requests()
    frozen = {s['slot']: s['prompt_sha256'] for s in record['qualification']['slots']} if 'qualification' in record \
        else json.loads(FREEZE_FILE.read_text(encoding='utf-8'))['qualification']['slots']
    if isinstance(frozen, list):
        frozen = {s['slot']: s['prompt_sha256'] for s in frozen}
    for slot in schedule():
        if slot['slot'] in state['ends']:
            continue
        if len(state['launches']) >= caps['max_launches']:
            return {'launched': launched, 'stopped': 'launch cap reached'}
        now = clock()
        first = state['first_launch'] if state['first_launch'] is not None else now
        if now - first >= caps['overall_seconds']:
            return {'launched': launched, 'stopped': 'overall time cap reached'}
        if _spent(state['ends'], caps['reserve_tokens']) + caps['reserve_tokens'] > caps['max_tokens']:
            return {'launched': launched, 'stopped': 'token ceiling: no room for another reservation'}
        request = reqs[slot['slot']]
        if B.sha(request['prompt']) != frozen.get(slot['slot']) or request['system'] != SYSTEM:
            return halt(f"slot {slot['slot']}: the request differs from the frozen bytes")
        call_id = uuid.uuid4().hex
        cdir = store.call_dir(slot)
        cdir.mkdir(parents=True, exist_ok=True)
        (cdir / 'request.json').write_text(json.dumps(request, ensure_ascii=False), encoding='utf-8')
        launch = {'event': 'launch', 'slot': slot['slot'], 'arm': slot['arm'], 'cell': slot['cell'],
                  'goal': slot['goal'], 'cases': slot['cases'], 'call_id': call_id, 'ts': now, 'at': B.iso(now),
                  'system_sha256': B.sha(request['system']), 'prompt_sha256': B.sha(request['prompt']),
                  'argv_flags': B.call_argv('<H>')[1:]}
        store.append(launch)
        state['launches'][slot['slot']] = launch
        state['first_launch'] = first
        launched += 1
        log(f"slot {slot['slot']:2d}/36 {slot['cell']} goal {slot['goal']} cases {slot['cases']} launching")
        started = clock()
        exit_code, stdout, stderr, timed_out = runner(request, caps['call_seconds'])
        elapsed_ms = int(round((clock() - started) * 1000))
        (cdir / 'envelope.json').write_bytes(stdout)
        (cdir / 'stderr.txt').write_bytes(stderr)
        evaluation = evaluate(exit_code, timed_out, elapsed_ms, stdout, slot['expected'], caps['call_seconds'])
        end = {'event': 'end', 'slot': slot['slot'], 'call_id': call_id, 'ts': clock(), 'at': B.iso(clock()),
               'stdout_sha256': B.sha(stdout), 'stderr_sha256': B.sha(stderr), 'evaluation': evaluation}
        (cdir / 'meta.json').write_text(json.dumps({'launch': launch, 'end': end}, indent=1), encoding='utf-8')
        store.append(end)
        state['ends'][slot['slot']] = end
        log(f"  -> {evaluation['outcome']}, {evaluation['correct_members']}/{len(slot['ids'])} right, tokens "
            f"{evaluation['usage']['total']}, thinking {evaluation['usage']['thinking']}, {elapsed_ms} ms")
        if not evaluation['passed']:
            why = ('route mismatch ' + str(evaluation['usage']['models']) if evaluation['route'] == 'mismatch'
                   else evaluation['outcome'] if evaluation['outcome'] != 'correct'
                   else 'not on time' if not evaluation['on_time'] else 'accounting incomplete')
            return halt(f"slot {slot['slot']} ({slot['cell']}) did not pass: {why}")
    return {'launched': launched, 'stopped': 'schedule complete'}


def analyze_qualification(out: Path = QUAL_OUT) -> dict:
    """Re-score every retained call from its raw envelope and give each cell's verdict: pass (every scheduled call of
    the cell passed), fail (a call of the cell did not pass, or an unfinished launch), untested (stopped before it) or
    incomplete. Evidence problems (changed output, re-scoring differences, ledger damage) make the verdict incomplete."""
    store = B.Store(out)
    events, problems = store.events()
    state = B.state_of(events)
    sched = {s['slot']: s for s in schedule()}
    rows = []
    for number, end in sorted(state['ends'].items()):
        slot = sched.get(number)
        cdir = store.call_dir(slot) if slot else None
        stdout = (cdir / 'envelope.json').read_bytes() if cdir and (cdir / 'envelope.json').exists() else b''
        stderr = (cdir / 'stderr.txt').read_bytes() if cdir and (cdir / 'stderr.txt').exists() else b''
        if slot is None:
            problems.append(f'slot {number} is not in the schedule')
            continue
        if B.sha(stdout) != end['stdout_sha256'] or B.sha(stderr) != end['stderr_sha256']:
            problems.append(f'slot {number}: retained output differs from its recorded digest')
        stored = end['evaluation']
        again = evaluate(stored['exit_code'], stored['timed_out'], stored['elapsed_ms'], stdout, slot['expected'],
                         qual()['caps']['call_seconds'])
        if again != stored:
            problems.append(f'slot {number}: re-scoring the retained output differs from the recorded evaluation')
        rows.append({'slot': number, 'cell': slot['cell'], 'goal': slot['goal'], 'cases': slot['cases'],
                     'outcome': again['outcome'], 'passed': again['passed'], 'correct_members': again['correct_members'],
                     'members': len(slot['ids']), 'tokens': again['usage']['total'],
                     'thinking': again['usage']['thinking'], 'seconds': round(again['elapsed_ms'] / 1000, 1),
                     'route': again['route']})
    cells = {}
    for cell, size in (('size4', 12), ('size1', 24)):
        rs = [r for r in rows if r['cell'] == cell]
        orphan = any(sched[n]['cell'] == cell for n in state['orphans'])
        if problems:
            verdict = 'incomplete'
        elif orphan or any(not r['passed'] for r in rs):
            verdict = 'fail'
        elif len(rs) == size:
            verdict = 'pass'
        else:
            verdict = 'untested' if not rs else 'incomplete'
        cells[cell] = {'verdict': verdict, 'calls': len(rs), 'scheduled': size,
                       'passed_calls': sum(r['passed'] for r in rs),
                       'tokens': sum(r['tokens'] or 0 for r in rs),
                       'calls_without_usage': sum(r['tokens'] is None for r in rs),
                       'thinking_per_call': [r['thinking'] for r in rs]}
    plan = state['plan'] or {}
    return {'digest': plan.get('digest'), 'rows': rows, 'cells': cells, 'problems': problems,
            'orphans': state['orphans'], 'tokens': sum(r['tokens'] or 0 for r in rows), 'launches': len(state['launches']),
            'pass': not problems and all(c['verdict'] == 'pass' for c in cells.values())}


