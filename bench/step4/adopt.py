def packet_problems(prompt: str, goal: str, members: list) -> list:
    """The value form and layout rule of the plan: v,goal,ops,refs,jobs; this goal and the frozen op text; records as
    JSON strings and intervals as JSON values (arrays, or the string unknown), interleaved per job in first-use order;
    one block, rows [classify_X, 2k, 2k+1] with X by position; no line break."""
    problems = []
    if '\n' in prompt or '\r' in prompt:
        problems.append('the prompt has a line break')
    body = json.loads(prompt)
    if list(body) != ['v', 'goal', 'ops', 'refs', 'jobs'] or body['v'] != '1g':
        return problems + ['not a 1g packet']
    if body['goal'] != goal:
        problems.append('goal differs')
    if body['ops'] != [spec()['model_ops']['model.classify']['instruction']]:
        problems.append('op text differs from model.classify v2')
    want_refs = [v for r, i in members for v in (r, i)]
    if body['refs'] != want_refs:
        problems.append('refs are not record, interval per job in order (value form)')
    if any(not isinstance(body['refs'][2 * k], str) for k in range(len(members))):
        problems.append('a record ref is not a JSON string')
    for k, (_, interval) in enumerate(members):
        raw = J(body['refs'][2 * k + 1])
        if raw != J(interval) or (interval != 'unknown' and not raw.startswith('[')):
            problems.append(f'interval ref {2 * k + 1} is not the JSON value')
    ids = qual()['job_ids'][:len(members)]
    if body['jobs'] != [[0, *[[j, 2 * k, 2 * k + 1] for k, j in enumerate(ids)]]]:
        problems.append('job block is not one row per member with its two refs in order')
    if J(body) != prompt:
        problems.append('prompt is not compact JSON')
    return problems


